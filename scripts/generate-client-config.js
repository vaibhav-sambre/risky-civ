'use strict';
// Generate js/config.js (ESM) from server/config.js (CommonJS, single source of truth).
// Run: node scripts/generate-client-config.js  OR  npm run sync

const fs = require('fs');
const path = require('path');

const config = require('../server/config');

const SHARED_KEYS = [
  'PLAYER_COLORS',
  'PLAYER_NAMES',
  'NEUTRAL_COLOR',
  'RESOURCE_TYPES',
  'STARTING_RESOURCES',
  'BASE_TERRITORY_RESOURCES',
  'STRUCTURES',
  'TROOP_DEPLOY_COST',
  'TROOP_UPKEEP_COST',
  'BASE_DEPLOY_COUNT',
  'MIN_GARRISON',
  'BASE_ACTIONS_PER_TURN',
  'MAX_ATTACK_DICE',
  'MAX_DEFEND_DICE',
  'DICE_SIDES',
  'STARTING_HAND_SIZE',
  'MAX_HAND_SIZE',
  'CARDS_DRAWN_PER_TURN',
  'WIN_TERRITORY_PERCENT',
  'TOTAL_TERRITORIES',
  'BONUS_CARDS',
  'EVENT_CARDS',
  'TECH_TREE',
];

const lines = [
  '// ── Risky Civ — Game Configuration (AUTO-GENERATED) ─────────────────',
  '// DO NOT EDIT THIS FILE DIRECTLY.',
  '// Edit server/config.js instead, then run: npm run sync',
  '// ─────────────────────────────────────────────────────────────────────',
  '',
];

for (const key of SHARED_KEYS) {
  if (!(key in config)) {
    console.warn(`WARNING: key "${key}" not found in server/config.js — skipping`);
    continue;
  }
  lines.push(`export const ${key} = ${JSON.stringify(config[key], null, 2)};`);
  lines.push('');
}

// CARD_DEFINITIONS is a client-only alias — server modules never use it.
lines.push('// Combined alias (client-only convenience export)');
lines.push('export const CARD_DEFINITIONS = [...BONUS_CARDS, ...EVENT_CARDS];');
lines.push('');

const outPath = path.resolve(__dirname, '../js/config.js');
fs.writeFileSync(outPath, lines.join('\n'), 'utf8');
console.log(`Generated ${outPath} (${SHARED_KEYS.length} shared exports)`);
